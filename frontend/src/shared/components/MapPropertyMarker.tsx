"use client";

/**
 * =========================================================
 * MapPropertyMarker
 * =========================================================
 *
 * Marker اختصاصی ملک روی نقشه
 *
 * وظیفه این کامپوننت:
 *
 * 1. نمایش موقعیت ملک
 * 2. دریافت کلیک کاربر
 * 3. اطلاع دادن ملک انتخاب‌شده به والد
 *
 * ---------------------------------------------------------
 * نکته معماری:
 *
 * این کامپوننت نباید تصمیم بگیرد بعد از انتخاب ملک
 * چه UIای نمایش داده شود.
 *
 * فقط می‌گوید:
 *
 * "این ملک انتخاب شد."
 *
 * تصمیم نمایش PropertyPreviewCard در
 * PropertySearchPage گرفته می‌شود.
 * =========================================================
 */

import {
  CircleMarker,
  Popup,
} from "react-leaflet";

import type { MapProperty } from "./map/RealMap";

/**
 * =========================================================
 * Props
 * =========================================================
 */

interface MapPropertyMarkerProps {
  /**
   * اطلاعات ملک
   */
  property: MapProperty;

  /**
   * Callback انتخاب ملک
   *
   * اختیاری است تا Marker در جاهایی که نیاز به
   * انتخاب ندارند نیز قابل استفاده باشد.
   */
  onSelect?: (
    property: MapProperty
  ) => void;
}

/**
 * =========================================================
 * Component
 * =========================================================
 */

export function MapPropertyMarker({
  property,
  onSelect,
}: MapPropertyMarkerProps) {
  return (
    <CircleMarker
      /**
       * ---------------------------------------------------
       * موقعیت Marker
       * ---------------------------------------------------
       *
       * Leaflet به صورت:
       *
       * [latitude, longitude]
       *
       * دریافت می‌کند.
       */
      center={[
        property.latitude,
        property.longitude,
      ]}

      /**
       * اندازه Marker
       */
      radius={9}

      /**
       * ---------------------------------------------------
       * ظاهر Marker
       * ---------------------------------------------------
       */

      pathOptions={{
        /**
         * رنگ داخل Marker
         */
        fillColor: "#0f172a",

        /**
         * میزان شفافیت داخل
         */
        fillOpacity: 0.95,

        /**
         * رنگ حاشیه
         */
        color: "#ffffff",

        /**
         * ضخامت حاشیه
         */
        weight: 3,
      }}

      /**
       * =================================================
       * رویدادهای Marker
       * =================================================
       *
       * وقتی کاربر روی Marker کلیک کند:
       *
       * property
       *
       * به صفحه Search ارسال می‌شود.
       */
      eventHandlers={{
        click: () => {
          onSelect?.(property);
        },
      }}
    >
      {/* =================================================
          Popup
          =================================================
          
          فعلاً یک Popup ساده Leaflet نیز داریم.
          
          در مرحله بعدی PropertyPreviewCard روی خود
          Search جایگزین تجربه اصلی Popup خواهد شد.
      ================================================= */}

      <Popup>
        <div
          dir="rtl"
          className="
            min-w-[190px]
            space-y-2
            text-right
          "
        >
          {/* ------------------------------------------------
              عنوان ملک
          ------------------------------------------------ */}

          <div
            className="
              text-sm
              font-bold
              text-slate-900
            "
          >
            {property.title}
          </div>

          {/* ------------------------------------------------
              محل ملک
          ------------------------------------------------ */}

          <div
            className="
              text-xs
              text-slate-500
            "
          >
            {property.location}
          </div>

          {/* ------------------------------------------------
              مشخصات
          ------------------------------------------------ */}

          <div
            className="
              flex
              gap-3
              text-xs
              text-slate-600
            "
          >
            <span>
              {property.area} متر
            </span>

            {property.rooms > 0 && (
              <span>
                {property.rooms} خواب
              </span>
            )}
          </div>

          {/* ------------------------------------------------
              قیمت
          ------------------------------------------------ */}

          <div
            className="
              pt-1
              text-sm
              font-bold
              text-slate-900
            "
          >
            {property.price}
          </div>
        </div>
      </Popup>
    </CircleMarker>
  );
}