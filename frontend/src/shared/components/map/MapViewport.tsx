
"use client";

/**
 * =========================================================
 * MapViewport
 * =========================================================
 *
 * وظیفه:
 *
 * تشخیص محدوده فعلی نقشه بعد از:
 *
 * - حرکت نقشه
 * - Zoom
 *
 * این کامپوننت خودش UI ندارد.
 *
 * فقط به Eventهای Leaflet گوش می‌دهد و محدوده فعلی
 * نقشه را از طریق onBoundsChange به والد اطلاع می‌دهد.
 *
 * =========================================================
 */

import { useEffect } from "react";

import { useMap } from "react-leaflet";

/**
 * =========================================================
 * محدوده نقشه
 * =========================================================
 */

export interface MapBounds {
  /**
   * عرض جغرافیایی شمالی‌ترین نقطه
   */
  north: number;

  /**
   * عرض جغرافیایی جنوبی‌ترین نقطه
   */
  south: number;

  /**
   * طول جغرافیایی شرقی‌ترین نقطه
   */
  east: number;

  /**
   * طول جغرافیایی غربی‌ترین نقطه
   */
  west: number;
}

/**
 * =========================================================
 * Props
 * =========================================================
 */

interface MapViewportProps {
  /**
   * هر بار محدوده نقشه تغییر کند،
   * این تابع با مختصات جدید اجرا می‌شود.
   */
  onBoundsChange?: (bounds: MapBounds) => void;
}

/**
 * =========================================================
 * MapViewport Component
 * =========================================================
 */

export function MapViewport({
  onBoundsChange,
}: MapViewportProps) {
  /**
   * دریافت instance واقعی Leaflet
   */
  const map = useMap();

  /**
   * =======================================================
   * دریافت محدوده اولیه + تغییرات نقشه
   * =======================================================
   */

  useEffect(() => {
    /**
     * -----------------------------------------------------
     * تابع دریافت محدوده فعلی نقشه
     * -----------------------------------------------------
     */

    const updateBounds = () => {
      /**
       * محدوده فعلی نقشه
       */
      const bounds = map.getBounds();

      /**
       * تبدیل اطلاعات Leaflet به ساختار ساده
       *
       * این ساختار بعداً مستقیماً می‌تواند
       * وارد Search API شود.
       */
      const mapBounds: MapBounds = {
        north: bounds.getNorth(),
        south: bounds.getSouth(),
        east: bounds.getEast(),
        west: bounds.getWest(),
      };

      /**
       * ارسال محدوده به والد
       */
      onBoundsChange?.(mapBounds);
    };

    /**
     * -----------------------------------------------------
     * محدوده اولیه
     * -----------------------------------------------------
     *
     * هنگام اولین اجرای نقشه هم محدوده را می‌گیریم.
     */
    updateBounds();

    /**
     * -----------------------------------------------------
     * حرکت نقشه
     * -----------------------------------------------------
     *
     * moveend بعد از پایان حرکت اجرا می‌شود.
     */
    map.on("moveend", updateBounds);

    /**
     * -----------------------------------------------------
     * Zoom
     * -----------------------------------------------------
     *
     * بعد از پایان Zoom هم محدوده تغییر می‌کند.
     */
    map.on("zoomend", updateBounds);

    /**
     * -----------------------------------------------------
     * Cleanup
     * -----------------------------------------------------
     */

    return () => {
      map.off("moveend", updateBounds);
      map.off("zoomend", updateBounds);
    };
  }, [map, onBoundsChange]);

  /**
   * این کامپوننت UI ندارد.
   */
  return null;
}

