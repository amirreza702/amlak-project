
"use client";

/**
 * =========================================================
 * SearchMap
 * =========================================================
 *
 * نقشه واقعی صفحه Search
 *
 * وظایف:
 *
 * 1. نمایش RealMap
 * 2. دریافت محدوده فعلی نقشه
 *
 * فعلاً:
 *
 * - داده‌ها Mock هستند.
 * - محدوده فقط در Console نمایش داده می‌شود.
 * - Backend هنوز متصل نشده است.
 *
 * در مرحله بعد:
 *
 * MapBounds
 *      ↓
 * Search API
 *      ↓
 * املاک داخل محدوده
 *
 * =========================================================
 */

import { useCallback } from "react";

import dynamic from "next/dynamic";

import type { MapBounds } from "@/shared/components/map/MapViewport";

/**
 * =========================================================
 * RealMap
 * =========================================================
 *
 * Leaflet در SSR نباید اجرا شود.
 *
 * بنابراین RealMap فقط در Browser لود می‌شود.
 *
 * این موضوع همان خطای:
 *
 * window is not defined
 *
 * را نیز جلوگیری می‌کند.
 * =========================================================
 */

const RealMap = dynamic(
  () =>
    import("@/shared/components/map/RealMap").then(
      (mod) => mod.RealMap
    ),
  {
    ssr: false,
  }
);

/**
 * =========================================================
 * SearchMap
 * =========================================================
 */

export function SearchMap() {
  /**
   * =======================================================
   * دریافت محدوده نقشه
   * =======================================================
   *
   * فعلاً فقط برای تست در Console چاپ می‌کنیم.
   *
   * بعداً همین تابع محل اتصال به Search API خواهد بود.
   * =======================================================
   */

  const handleBoundsChange = useCallback(
    (bounds: MapBounds) => {
      console.log(
        "Map bounds:",
        bounds
      );
    },
    []
  );

  return (
    <div
      className="
        absolute
        inset-0
        z-0
        overflow-hidden
      "
    >
      {/* =================================================
          نقشه واقعی
         ================================================= */}

      <RealMap
        onBoundsChange={handleBoundsChange}
      />

      {/* =================================================
          لایه بسیار ملایم روی نقشه
          
          pointer-events-none باعث می‌شود این لایه
          مانع تعامل کاربر با نقشه نشود.
         ================================================= */}

      <div
        className="
          pointer-events-none
          absolute
          inset-0
          z-[1]
          bg-white/5
        "
      />
    </div>
  );
}

